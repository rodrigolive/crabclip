//! Turns raw pasteboard representations (+ source metadata) into a `NewClip`:
//! picks the kind, extracts searchable text, file paths and source URL, measures
//! and thumbnails images, applies the optional image downscale rule, and hashes
//! the content for de-duplication. Shared by live capture and the importers.

use crate::db::{AppInfo, Kind, NewClip, PREVIEW_CHARS, Rep};
use crate::settings::Settings;

#[derive(Clone, Debug, Default)]
pub struct Capture {
    pub ts: i64,
    pub reps: Vec<Rep>,
    pub app: AppInfo,
    pub window_title: Option<String>,
    pub source_path: Option<String>,
    pub starred: bool,
}

/// Types that mean "do not record this" (password managers, transient data).
pub const SKIP_MARKERS: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
];

pub const IMAGE_TYPES: &[&str] = &[
    "public.png",
    "public.tiff",
    "public.jpeg",
    "public.heic",
    "com.compuserve.gif",
    "org.webmproject.webp",
    "com.microsoft.bmp",
    "com.adobe.pdf",
];

/// Old NSPasteboard names that duplicate a modern UTI in the same item.
const LEGACY: &[(&str, &str)] = &[
    ("NeXT TIFF v4.0 pasteboard type", "public.tiff"),
    ("Apple PNG pasteboard type", "public.png"),
    ("NSStringPboardType", "public.utf8-plain-text"),
    ("Apple HTML pasteboard type", "public.html"),
    ("NeXT Rich Text Format v1.0 pasteboard type", "public.rtf"),
    ("NeXT RTFD pasteboard type", "com.apple.flat-rtfd"),
    ("Apple Web Archive pasteboard type", "com.apple.webarchive"),
    ("Apple URL pasteboard type", "public.url"),
    ("CorePasteboardFlavorType 0x75743136", "public.utf16-external-plain-text"),
    ("CorePasteboardFlavorType 0x6675726C", "public.file-url"),
    ("Apple PDF pasteboard type", "com.adobe.pdf"),
];

pub fn drop_legacy(reps: Vec<Rep>) -> Vec<Rep> {
    let present: std::collections::HashSet<(i64, String)> =
        reps.iter().map(|r| (r.item, r.uti.clone())).collect();
    reps.into_iter()
        .filter(|r| {
            !LEGACY.iter().any(|(old, new)| {
                r.uti == *old && present.contains(&(r.item, new.to_string()))
            })
        })
        .collect()
}

fn find<'a>(reps: &'a [Rep], uti: &str) -> Option<&'a Rep> {
    reps.iter().find(|r| r.uti == uti)
}

pub fn percent_decode(s: &str) -> String {
    fn hex(c: u8) -> Option<u8> {
        (c as char).to_digit(16).map(|d| d as u8)
    }
    let b = s.as_bytes();
    let mut out = Vec::with_capacity(b.len());
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'%' && i + 2 < b.len() {
            if let (Some(h), Some(l)) = (hex(b[i + 1]), hex(b[i + 2])) {
                out.push(h << 4 | l);
                i += 3;
                continue;
            }
        }
        out.push(b[i]);
        i += 1;
    }
    String::from_utf8_lossy(&out).into_owned()
}

/// "file:///Users/x/a%20b.txt" -> "/Users/x/a b.txt"
pub fn file_url_to_path(url: &str) -> Option<String> {
    let rest = url.trim().trim_end_matches('\0').strip_prefix("file://")?;
    let rest = rest.strip_prefix("localhost").unwrap_or(rest);
    let mut p = percent_decode(rest);
    if p.len() > 1 && p.ends_with('/') {
        p.pop();
    }
    Some(p)
}

fn utf16(data: &[u8]) -> String {
    let (le, body) = match data {
        [0xFF, 0xFE, rest @ ..] => (true, rest),
        [0xFE, 0xFF, rest @ ..] => (false, rest),
        _ => (true, data),
    };
    let units: Vec<u16> = body
        .chunks_exact(2)
        .map(|c| if le { u16::from_le_bytes([c[0], c[1]]) } else { u16::from_be_bytes([c[0], c[1]]) })
        .collect();
    String::from_utf16_lossy(&units)
}

pub fn text_of(reps: &[Rep]) -> Option<String> {
    let t = if let Some(r) = find(reps, "public.utf8-plain-text") {
        String::from_utf8_lossy(&r.data).into_owned()
    } else if let Some(r) = find(reps, "public.utf16-external-plain-text").or_else(|| find(reps, "public.utf16-plain-text")) {
        utf16(&r.data)
    } else if let Some(r) = find(reps, "NSStringPboardType") {
        String::from_utf8_lossy(&r.data).into_owned()
    } else {
        return None;
    };
    let t = t.trim_end_matches('\0').to_string();
    if t.trim().is_empty() { None } else { Some(t) }
}

/// Some apps copy a file reference URL (`file:///.file/id=…`) instead of the
/// file's path. Turn each into the path URL it points to, while the file is
/// there to resolve. True when one changed.
pub fn resolve_file_refs(reps: &mut [Rep]) -> bool {
    let mut changed = false;
    for r in reps.iter_mut().filter(|r| r.uti == "public.file-url") {
        let url = String::from_utf8_lossy(&r.data).trim().trim_end_matches('\0').to_string();
        if !url.starts_with("file:///.file/id=") {
            continue;
        }
        let resolved = objc2_foundation::NSURL::URLWithString(&objc2_foundation::NSString::from_str(&url))
            .and_then(|u| u.filePathURL())
            .and_then(|u| u.absoluteString());
        if let Some(u) = resolved {
            r.data = u.to_string().into_bytes();
            changed = true;
        }
    }
    changed
}

pub fn file_paths(reps: &[Rep]) -> Vec<String> {
    let mut v: Vec<String> = reps
        .iter()
        .filter(|r| r.uti == "public.file-url")
        .filter_map(|r| file_url_to_path(&String::from_utf8_lossy(&r.data)))
        .collect();
    v.dedup();
    v
}

pub fn is_url(t: &str) -> bool {
    let t = t.trim();
    !t.contains(char::is_whitespace)
        && (t.starts_with("http://") || t.starts_with("https://") || t.starts_with("ftp://"))
        && t.len() > 10
}

/// Source page URL from browser-specific pasteboard types.
fn source_url(reps: &[Rep]) -> Option<String> {
    if let Some(r) = find(reps, "org.chromium.source-url") {
        let s = String::from_utf8_lossy(&r.data).trim_end_matches('\0').trim().to_string();
        if !s.is_empty() {
            return Some(s);
        }
    }
    if let Some(r) = find(reps, "com.apple.webarchive") {
        if let Ok(v) = plist::Value::from_reader(std::io::Cursor::new(&r.data)) {
            if let Some(u) = v
                .as_dictionary()
                .and_then(|d| d.get("WebMainResource"))
                .and_then(|m| m.as_dictionary())
                .and_then(|m| m.get("WebResourceURL"))
                .and_then(|u| u.as_string())
            {
                if !u.starts_with("about:") && !u.is_empty() {
                    return Some(u.to_string());
                }
            }
        }
    }
    None
}

pub fn primary_image(reps: &[Rep]) -> Option<&Rep> {
    IMAGE_TYPES.iter().filter(|t| **t != "com.adobe.pdf").find_map(|t| find(reps, t))
}

pub fn preview_of(text: &str) -> String {
    let t = text.trim_start_matches(['\n', '\r']);
    let mut s: String = t.chars().take(PREVIEW_CHARS).collect();
    s = s.replace("\r\n", "\n").replace('\r', "\n").replace('\t', "    ");
    s
}

fn kind_of(text: Option<&str>, has_image: bool, files: &[String], reps: &[Rep]) -> Kind {
    let rich = find(reps, "public.rtf").is_some() || find(reps, "public.html").is_some();
    if !files.is_empty() {
        Kind::File
    } else if has_image && (text.is_none() || (!rich && text.is_some_and(is_url))) {
        Kind::Image
    } else if let Some(t) = text {
        if is_url(t) { Kind::Url } else { Kind::Text }
    } else if has_image {
        Kind::Image
    } else {
        Kind::Other
    }
}

/// The de-duplication hash of a clip's content (also used to restore it when
/// it stops being a sealed password).
pub fn content_hash(kind: Kind, reps: &[Rep]) -> Option<Vec<u8>> {
    let mut h = blake3::Hasher::new();
    h.update(kind.as_str().as_bytes());
    match kind {
        Kind::Text | Kind::Url => {
            h.update(text_of(reps).as_deref().unwrap_or("").as_bytes());
        }
        Kind::File => {
            h.update(file_paths(reps).join("\n").as_bytes());
        }
        Kind::Image => {
            h.update(&primary_image(reps)?.data);
        }
        Kind::Other => {
            for r in reps {
                h.update(r.uti.as_bytes());
                h.update(&r.data);
            }
        }
    }
    Some(h.finalize().as_bytes().to_vec())
}

/// Build the clip to store. Returns None when there is nothing worth keeping.
pub fn build(c: Capture, s: &Settings) -> Option<NewClip> {
    // Marker types are often empty: check them before dropping empty data.
    if c.reps.iter().any(|r| SKIP_MARKERS.contains(&r.uti.as_str())) {
        return None;
    }
    let mut reps = drop_legacy(c.reps);
    reps.retain(|r| !r.data.is_empty());
    resolve_file_refs(&mut reps);
    if reps.is_empty() {
        return None;
    }
    let files = file_paths(&reps);
    let text = text_of(&reps);
    let has_image = primary_image(&reps).is_some();
    let kind = kind_of(text.as_deref(), has_image, &files, &reps);

    let mut img = None;
    let mut thumb = None;
    if kind == Kind::Image {
        let prim = primary_image(&reps)?.clone();
        let mut info = crate::imageio::info(&prim.data);
        if let Some(i) = info {
            let mp = (i.width * i.height) as f64 / 1e6;
            if s.img_scale_pct < 100 && mp > s.img_scale_min_mp {
                let max_px = (i.width.max(i.height) as f64 * s.img_scale_pct as f64 / 100.0) as usize;
                for r in reps.iter_mut() {
                    if IMAGE_TYPES.contains(&r.uti.as_str()) && r.uti != "com.adobe.pdf" {
                        if let Some(d) = crate::imageio::scaled(&r.data, max_px, &r.uti) {
                            r.data = d;
                        }
                    }
                }
                info = primary_image(&reps).and_then(|p| crate::imageio::info(&p.data));
            }
        }
        if let Some(i) = info {
            img = Some((i.width, i.height, i.scale));
        }
        let prim = primary_image(&reps)?;
        thumb = crate::imageio::thumbnail(&prim.data, 760, 300);
    }

    let mut body_text = text.clone();
    if kind == Kind::File {
        body_text = Some(files.join("\n"));
    }
    let preview = match kind {
        Kind::File => files.join("\n"),
        Kind::Other => reps.iter().map(|r| r.uti.as_str()).collect::<Vec<_>>().join(", "),
        _ => body_text.as_deref().map(preview_of).unwrap_or_default(),
    };

    let hash = content_hash(kind, &reps)?;

    let mut types: Vec<&str> = Vec::new();
    for r in &reps {
        if !types.contains(&r.uti.as_str()) {
            types.push(&r.uti);
        }
    }
    let source_path = c
        .source_path
        .or_else(|| if files.len() == 1 { files.first().cloned() } else { None });
    let mut src_url = source_url(&reps);
    if src_url.is_none() && kind != Kind::Url {
        src_url = find(&reps, "public.url")
            .map(|r| String::from_utf8_lossy(&r.data).trim_end_matches('\0').to_string())
            .filter(|u| !u.starts_with("file://") && !u.is_empty());
    }

    Some(NewClip {
        ts: c.ts,
        kind,
        hash,
        text: body_text,
        preview,
        app: c.app,
        window_title: c.window_title.filter(|t| !t.is_empty()),
        source_path,
        source_url: src_url,
        img,
        thumb,
        types: types.join(","),
        reps,
        starred: c.starred,
    })
}
